# ambientes virtuais em Python (venv)
# Um ambiente virtual carrega toda sua instalação
# do Python para uma pasta no caminho escolhido.
# Ao ativar um ambiente virtual, a instalação do ambinete
# virtual será usada.
# venv é o módulo que vamos usar para criar ambientes virtuais
# Você pode dar o nome que preferir para um ambiente virtual, mas os 
# mais comuns são:
# venv env ,env . venv

